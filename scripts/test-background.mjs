import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import path from 'node:path';
import fs from 'node:fs';
const req = createRequire(path.join(process.argv[2], 'package.json'));
const {chromium} = req('playwright');
const out = process.argv[3];
fs.mkdirSync(out, {recursive:true});
const origin = process.env.PULSE_PREVIEW_ORIGIN || 'http://127.0.0.1:5261';
const browser = await chromium.launch({channel:'msedge',headless:true});
const page = await browser.newPage({viewport:{width:640,height:940}});
const checks=[], errors=[], remote=[];
page.on('pageerror', e=>errors.push(String(e)));
page.on('console',m=>{if(['error','warning'].includes(m.type())&&!m.text().includes('[vite]'))errors.push(m.text());});
page.on('request',r=>{if(/^https?:/.test(r.url())&&!r.url().startsWith(origin+'/'))remote.push(r.url());});
await page.route('**/*',route=>/^https?:/.test(route.request().url())&&!route.request().url().startsWith(origin+'/')?route.abort():route.continue());
const check=(name,value)=>{assert.ok(value,name);checks.push(name);console.log('PASS '+name);};
const visit=async(width=248)=>{await page.goto(`${origin}/?mode=hero&width=${width}`);await page.locator('.pr-row').first().waitFor();};
const toggle=()=>page.getByRole('switch',{name:/Background collection/});
try {
  await visit();
  check('default footer collects while open',await page.locator('.pr-foot').textContent().then(s=>s.includes('Collecting while open')));
  const beacon=()=>page.locator('.pr-beacon').evaluate(e=>({label:e.getAttribute('aria-label'),title:e.getAttribute('title'),collector:e.getAttribute('data-collector'),hollow:getComputedStyle(e).backgroundColor==='rgba(0, 0, 0, 0)'}));
  check('viewed mode beacon reports collecting while open',await beacon().then(b=>b.label==='Live'&&b.title==='Collecting while open'&&!b.hollow));
  check('mount never opts into collection',await page.evaluate(()=>!window.__pulseRestCalls.some(c=>c.method==='PUT')));
  await page.getByRole('button',{name:'Pulse options',exact:true}).click();
  check('default background switch is off',await toggle().getAttribute('aria-checked')==='false');
  await toggle().click();
  await page.waitForFunction(()=>window.__pulseStatus.collection.mode==='background');
  await page.waitForFunction(()=>document.querySelector('[role=switch]')?.getAttribute('aria-checked')==='true');
  check('human click sends exact strict consent once',await page.evaluate(()=>{const calls=window.__pulseRestCalls.filter(c=>c.method==='PUT');return calls.length===1&&calls[0].path==='/settings'&&calls[0].body.confirm===true&&calls[0].body.background_collection===true;}));
  check('saved setting read back before status refresh',await page.evaluate(()=>{const cs=window.__pulseRestCalls;const i=cs.findIndex(c=>c.method==='PUT');return cs[i+1].path==='/settings'&&cs[i+1].method==='GET'&&cs.slice(i+2).some(c=>c.path==='/status');}));
  check('background footer reflects readback',await page.locator('.pr-foot').textContent().then(s=>s.includes('Collecting in background')));
  await page.screenshot({path:path.join(out,'background-on.png'),fullPage:true});
  check('background on without a live collector lease never announces Live',await beacon().then(b=>b.label==='Background collection not confirmed'&&!/live|collecting in background/i.test(b.label+' '+b.title)&&b.collector==='unconfirmed'&&b.hollow));
  check('unconfirmed collector keeps Live out of the heading name',await page.getByRole('heading',{name:/Live/}).count()===0);
  await page.evaluate(()=>{const s=window.__pulseStatus;s.collection={...s.collection,lease_holder_alive:true,last_tick_ts:s.as_of};window.__emitPulse('draft.updated');});
  await page.waitForFunction(()=>document.querySelector('.pr-beacon')?.getAttribute('data-collector')==='alive');
  check('a live collector lease confirms background collection',await beacon().then(b=>b.label==='Live'&&b.title==='Collecting in background'&&!b.hollow));
  await page.evaluate(()=>{const s=window.__pulseStatus;s.collection={...s.collection,lease_holder_alive:false,last_tick_ts:s.as_of-3600};window.__emitPulse('draft.updated');});
  await page.waitForFunction(()=>document.querySelector('.pr-beacon')?.getAttribute('data-collector')==='unconfirmed');
  check('an expired lease with an old tick drops the Live claim again',await beacon().then(b=>b.label==='Background collection not confirmed'&&b.hollow));
  await page.screenshot({path:path.join(out,'background-unconfirmed.png'),fullPage:true});
  await page.evaluate(()=>window.__setPaneVisible(false));await page.waitForTimeout(200);
  check('hidden pane does not toggle saved collection',await page.evaluate(()=>window.__pulseStatus.collection.mode==='background'&&window.__pulseRestCalls.filter(c=>c.method==='PUT').length===1));
  await page.evaluate(()=>window.__setPaneVisible(true));
  await toggle().click();await page.waitForFunction(()=>document.querySelector('[role=switch]')?.getAttribute('aria-checked')==='false');
  check('human off returns viewed footer',await page.locator('.pr-foot').textContent().then(s=>s.includes('Collecting while open')));
  await page.evaluate(()=>{window.__settingsError=true;});await toggle().click();
  await page.getByRole('alert').filter({hasText:'not saved'}).waitFor();
  check('failed write stays off and controls recover',await toggle().getAttribute('aria-checked')==='false'&&!await toggle().isDisabled());
  await visit();await page.getByRole('button',{name:'Pulse options',exact:true}).click();
  await page.evaluate(()=>{window.__settingsDelay=400;});await toggle().click();
  await page.evaluate(()=>window.__setPulseProfile('other-profile'));await page.waitForTimeout(700);
  check('profile switch never reads late old setting in new profile',await page.evaluate(()=>{const cs=window.__pulseRestCalls,i=cs.findIndex(c=>c.method==='PUT');return i>=0&&!cs.slice(i+1).some(c=>c.path==='/settings'&&c.profile==='preview');}));
  await page.getByRole('button',{name:'Pulse options',exact:true}).click();
  check('profile switch releases busy UI',!await toggle().isDisabled());
  for(const width of [176,200,248,320]) {
    await visit(width);
    check(`${width}px footer does not overflow`,await page.locator('.pr-shell').evaluate(e=>e.scrollWidth<=e.clientWidth+1));
  }
  check('no remote requests',remote.length===0);
  check('no runtime warnings',errors.length===0);
  fs.writeFileSync(path.join(out,'background-results.json'),JSON.stringify({checks,errors,remote},null,2));
  console.log(`${checks.length} background browser checks passed`);
} finally {await browser.close();}
