import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import {compatibleField, pause} from './builder2-test-helpers.mjs';
const {chromium}=createRequire(path.join(process.argv[2],'package.json'))('playwright');
const out=process.argv[3];fs.mkdirSync(out,{recursive:true});
const origin=process.env.PULSE_PREVIEW_ORIGIN || 'http://127.0.0.1:5461';
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:1420,height:1100},reducedMotion:'reduce'});
page.setDefaultTimeout(12000);
const errors=[],remote=[],checks=[];
page.on('pageerror',e=>errors.push(String(e)));
page.on('request',r=>{if(/^https?:/.test(r.url())&&!r.url().startsWith(origin+'/'))remote.push(r.url());});
await page.route('**/*',r=>/^https?:/.test(r.request().url())&&!r.request().url().startsWith(origin+'/')?r.abort():r.continue());
const check=(name,ok)=>{assert.ok(ok,name);checks.push(name);console.log('PASS '+name);};
const button=name=>page.getByRole('button',{name,exact:true});
try {
  await page.goto(`${origin}/?mode=blocks&width=320`,{timeout:60000});
  await page.locator('[data-id=synthetic-ebay] .pr-trigger').click();
  // Explicit synthetic computed rows exercise the renderer boundary, not GitHub.
  const setStat=async row=>{await page.evaluate(row=>{const p=window.__pulseStatus.pulses.find(p=>p.id==='synthetic-ebay');p.display[2]={type:'stat',index:2,label:'CI build',show:'value',delta:null,delta_text:null,caption:'',unknown:false,...row};window.__emitPulse('draft.updated');},row);await page.waitForTimeout(100);};
  const stat=page.locator('.pr-display .pr-stat__value');
  await setStat({value:1,value_text:'Passing',tone:'ok',discrete:true});
  check('Passing is measured text, not numeric animation',await stat.textContent()==='Passing'&&await stat.locator('.pr-number').count()===0&&await stat.locator('..').getAttribute('data-state')==='measured');
  const okColor=await stat.evaluate(el=>getComputedStyle(el).color);
  await setStat({value:0,value_text:'Failing',tone:'crit',discrete:true});
  check('Failing uses a distinct critical tone',await stat.textContent()==='Failing'&&await stat.locator('..').getAttribute('data-tone')==='crit'&&await stat.evaluate(el=>getComputedStyle(el).color)!==okColor);
  await setStat({value_text:'<img src=x onerror=alert(1)>',discrete:true});
  check('state labels are literal text, never markup',await stat.textContent()==='<img src=x onerror=alert(1)>'&&await stat.locator('img').count()===0);
  await setStat({unknown:true,reason:'needs Actions read access',value_text:null,tone:'ok',discrete:true});
  check('unknown keeps reason and removes tone',await stat.textContent()==='needs Actions read access'&&await stat.locator('..').getAttribute('data-tone')==='none');
  await setStat({value:3.2,value_text:'3h 12m ago',duration:true});
  check('duration text is not numerically animated',await stat.textContent()==='3h 12m ago'&&await stat.locator('.pr-number').count()===0);
  await page.goto(`${origin}/?mode=builder&width=900`);await button('New pulse').click();await pause(page);
  await page.locator('.pr-b2-template').first().waitFor({timeout:30000}).catch(async e=>{console.log(await page.locator('body').innerText());throw e;});
  await page.locator('.pr-b2-template').filter({has:page.getByText('GitHub repo',{exact:true})}).click();await pause(page);
  await compatibleField(page,'/template/repo').fill('Stormxftw/Pulse');
  for(const key of ['commits','last_push','ci'])await compatibleField(page,'/template/'+key).check();
  await pause(page);check('all three optional checkboxes are real inputs',await compatibleField(page,'/template/ci').isChecked());
  await button('Next').click();await pause(page);
  check('Repo activity is the selected recommended preset',await page.locator('.pr-b2-layout[aria-pressed=true]').innerText().then(t=>t.includes('Repo activity')));
  check('repo preset has score and two stats',await page.locator('.pr-builder-preview .pr-block[data-type=score]').count()===1&&await page.locator('.pr-builder-preview .pr-block[data-type=stat]').count()===2);
  await button('Next').click();await pause(page);
  check('review discloses both opts and 13 req/h at default 15m',await page.locator('.pr-b2-review-summary').innerText().then(t=>t.includes('api.github.com')&&t.includes('13')));
  await button('Review permissions').click();await page.locator('.pr-builder-review .pr-approval').waitFor();
  const approval=await page.locator('.pr-builder-review .pr-approval').innerText();
  check('approval card discloses participation and Actions allocations',approval.includes('participation')&&approval.includes('1 req/h')&&approval.includes('actions/runs')&&approval.includes('1 call per poll'));
  check('never approves automatically',await page.evaluate(()=>!window.__pulseRestCalls.some(c=>c.path.endsWith('/approve'))));
  check('no remote requests or page errors',remote.length===0&&errors.length===0);
  await page.screenshot({path:path.join(out,'repo-approval.png'),fullPage:true});
  fs.writeFileSync(path.join(out,'repo-activity-results.json'),JSON.stringify({checks:checks.length,errors,remote},null,2));
  console.log(`${checks.length} repo activity browser checks passed`);
} finally {await browser.close();}
